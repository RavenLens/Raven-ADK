import vm from 'node:vm';
import { RLMSubModel } from './orchestrator';

interface Sandbox {
    contextData: string,
    llmQuery: (inst: string, snip: string, modelIndex?: number) => Promise<string>,
    console: {
        log: (...args: any[]) => any,
        error: (...args: any[]) => any
    },
    submodels: Array<{model: any, instruction?: string}>,
    /** The storage for Context model answer */
    finalAnswer?: string,
    // A way for the agent to signal it has found the final answer
    submitFinalAnswer: (answer: string) => any
}

export class RLMEnvironment {
    hugeContextData: string;
    submodels: RLMSubModel[];
    logs: any[];
    callLLM?: (systemPrompt: string, userPrompt: string, options?: any) => Promise<string>;
    
    constructor(
        hugeContextData: string,
        submodels: RLMSubModel[],
        callLLM?: (systemPrompt: string, userPrompt: string, options?: any) => Promise<string>
    ) {
        this.hugeContextData = hugeContextData;
        this.submodels = submodels;
        this.logs = [];
        this.callLLM = callLLM;
    }

    // This is the RECURSIVE function exposed to the LLM
    // Supports model selection for CodeAct pattern delegation
    async llmQuery(instruction: string, snippet: string, modelIndex: number = 0) {
        if (!this.callLLM) {
            throw new Error("callLLM function not initialized in RLMEnvironment");
        }

        // Validate model index
        if (modelIndex < 0 || modelIndex >= this.submodels.length) {
            console.warn(`Invalid model index ${modelIndex}, using default model 0`);
            modelIndex = 0;
        }

        const selectedSubmodel = this.submodels[modelIndex];
        const modelSpec = selectedSubmodel.model;

        const prompt = `${instruction}\n\nContext Snippet:\n${snippet}`;
        
        // Call the LLM with the selected sub-model
        // Sub-models typically use cheaper/faster variants than the orchestrator
        const response = await this.callLLM(
            "You are a helpful sub-agent analyzer specializing in code and data analysis.",
            prompt,
            { model: modelSpec }
        );
        
        return response;
    }

    // Executes the JS code generated by the Orchestrator
    async executeAgentCode(code: string) {
        this.logs = []; // Clear logs for this run
        
        // Define the Sandbox context
        const sandbox: Sandbox = {
            contextData: this.hugeContextData,
            finalAnswer: undefined,
            submodels: this.submodels,
            llmQuery: (inst: string, snip: string, modelIndex?: number) => 
                this.llmQuery(inst, snip, modelIndex ?? 0),
            console: {
                log: (...args: any[]) => this.logs.push(args.join(' ')),
                error: (...args: any[]) => this.logs.push(`ERROR: ${args.join(' ')}`)
            },
            // A way for the agent to signal it has found the final answer
            submitFinalAnswer: (answer: string) => { sandbox.finalAnswer = answer; }
        };

        const vmContext = vm.createContext(sandbox);

        // Wrap the agent's code in an async IIFE to support top-level await
        const wrappedCode = `
            (async () => {
                try {
                    ${code}
                } catch (err) {
                    console.error(err.message);
                }
            })();
        `;

        const script = new vm.Script(wrappedCode);
        
        try {
            await script.runInContext(vmContext);
            return {
                output: this.logs.join('\n'),
                finalAnswer: vmContext.finalAnswer
            };
        } catch (error: any) {
            return { output: `Execution Error: ${error.message}`, finalAnswer: null };
        }
    }
}
